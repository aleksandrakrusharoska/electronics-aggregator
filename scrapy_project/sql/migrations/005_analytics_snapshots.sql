-- =====================================================================
-- 005 Пред-пресметана аналитика
--
-- Графиконите на страницата „Аналитика“ се пресметуваат од сите огласи
-- (страница по страница низ ads_view), што трае по неколку секунди. Се
-- чуваа еден час во меморијата на сервисот, но Render го приспива
-- сервисот по 15 минути без посети, па првото отворање по секое будење
-- пак ги пресметуваше директно. Податоците се менуваат еднаш дневно (по
-- pipeline-от), затоа дневниот workflow ги пресметува однапред
-- (backend/precompute_analytics.py) и ги запишува тука, а API-то само ги
-- чита.
--   name         графиконот и параметрите, на пр. 'brands:source=pazar3'
--   data         готовиот JSON што го враќа API-то
--   computed_at  кога е пресметан
-- =====================================================================

create table if not exists public.analytics_snapshots (
    name        text primary key,
    data        jsonb       not null,
    computed_at timestamptz not null default now()
);

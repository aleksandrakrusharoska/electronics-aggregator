-- 7. Поглед за читање ---------------------------------------------------
-- API-то и фронтендот читаат од ads_view, во истиот рамен облик како
-- досега, додека запишувањето оди во нормализираните табели.
-- LEFT JOIN насекаде: PostgreSQL ги прескокнува спојувањата чии колони не
-- се бараат (на пр. при броење), а оглас без анализа сепак се прикажува.

create view public.ads_view with (security_invoker = true) as
select
    a.ad_url,
    s.name               as source,
    a.title,
    a.description,
    a.price_amount,
    a.currency,
    a.price_mkd,
    round(a.price_mkd / 61.5, 2) as price_eur,
    c.name               as category,
    l.name               as location,
    a.images,
    a.seller_name,
    a.seller_type,
    a.posted_date,
    a.listing_type,
    a.condition,
    a.specs,
    a.scraped_at,
    a.created_at,
    a.is_active,
    aa.ad_type,
    aa.is_electronics,
    b.name               as brand,
    m.name               as model,
    aa.seller_notes,
    aa.phone,
    aa.delivery_available,
    aa.cluster_id,
    k.label              as cluster_label,
    -- која од двете цени на моделот важи за огласот, го кажува reference_source
    case aa.reference_source
        when 'marketplace'  then m.market_new_price_mkd
        when 'llm_estimate' then m.estimated_new_price_mkd
    end                  as reference_new_price_mkd,
    case aa.reference_source
        when 'marketplace'  then m.market_sample_size
        when 'llm_estimate' then 1
    end                  as reference_sample_size,
    aa.reference_source,
    aa.price_vs_new_ratio,
    aa.good_price_deal,
    aa.llm_parsed_at,
    a.source_id,
    a.category_id,
    a.location_id,
    aa.brand_id,
    aa.model_id
from public.ads a
left join public.sources     s  on s.source_id   = a.source_id
left join public.categories  c  on c.category_id = a.category_id
left join public.locations   l  on l.location_id = a.location_id
left join public.ad_analysis aa on aa.ad_url     = a.ad_url
left join public.brands      b  on b.brand_id    = aa.brand_id
left join public.models      m  on m.model_id    = aa.model_id
left join public.clusters    k  on k.cluster_id  = aa.cluster_id;


-- 8. Функцијата што ја чита Orchestrator Agent ---------------------------

create or replace function public.pipeline_status()
returns table(total bigint, classified bigint, products bigint, services bigint, wanted bigint,
              parsed bigint, clustered bigint, referenced bigint, duplicate_pairs bigint, estimated bigint)
language sql stable
as $$
    select
        a.total, a.classified, a.products, a.services, a.wanted,
        a.parsed, a.clustered, a.referenced,
        (select count(*) from public.duplicates) as duplicate_pairs,
        (select count(*) from public.models where estimated_new_price_mkd is not null) as estimated
    from (
        select
            count(*)                                                 as total,
            count(*) filter (where aa.ad_type is not null)           as classified,
            count(*) filter (where aa.ad_type = 'product')           as products,
            count(*) filter (where aa.ad_type = 'service')           as services,
            count(*) filter (where aa.ad_type = 'wanted')            as wanted,
            count(*) filter (where aa.llm_parsed_at is not null)     as parsed,
            count(*) filter (where aa.cluster_id is not null)        as clustered,
            count(*) filter (where aa.price_vs_new_ratio is not null) as referenced
        from public.ads a
        left join public.ad_analysis aa on aa.ad_url = a.ad_url
    ) a;
$$;

-- Бројките за страничната лента на апликацијата (/api/ads/stats) во едно
-- барање, наместо 8 одделни броења кои повремено паѓаа со statement timeout.
-- Ист филтер како листата: исклучени се само огласите потврдени дека не се
-- електроника (is_electronics = false).
create or replace function public.ad_stats()
returns json
language sql stable
as $$
    select json_build_object(
        'total',   count(*) filter (where e),
        'sources', json_build_object(
            'pazar3',   count(*) filter (where e and s.name = 'pazar3'),
            'reklama5', count(*) filter (where e and s.name = 'reklama5')),
        'duplicates', (select count(*) from public.duplicates),
        'good_deals', count(*) filter (where aa.good_price_deal),
        'ad_types', json_build_object(
            'product', count(*) filter (where e and aa.ad_type = 'product'),
            'service', count(*) filter (where e and aa.ad_type = 'service'),
            'wanted',  count(*) filter (where e and aa.ad_type = 'wanted')))
    from public.ads a
    left join public.sources s on s.source_id = a.source_id
    left join public.ad_analysis aa on aa.ad_url = a.ad_url
    cross join lateral (select aa.is_electronics is distinct from false as e) f;
$$;

-- Најчестите 40 категории со број на огласи (/api/ads/categories). Иста
-- ознака може да постои на двата портала, па се групира по име. Досега API-то
-- ги поминуваше сите огласи на страници од по 1.000 при секое вчитување.
create or replace function public.category_counts()
returns table(name text, count bigint)
language sql stable
as $$
    select c.name, count(*)
    from public.ads a
    join public.categories c on c.category_id = a.category_id
    group by c.name
    order by count(*) desc
    limit 40;
$$;

commit;


-- 1. Шифрарници -------------------------------------------------------

create table public.sources (
    source_id integer generated by default as identity primary key,
    name      text not null unique,
    base_url  text
);

create table public.categories (
    category_id integer generated by default as identity primary key,
    source_id   integer not null references public.sources (source_id),
    name        text    not null,
    unique (source_id, name)
);

create table public.locations (
    location_id integer generated by default as identity primary key,
    name        text not null unique
);

create table public.brands (
    brand_id integer generated by default as identity primary key,
    name     text not null
);
-- „HP“ и „Hp“ се ист бренд
create unique index brands_name_lower_key on public.brands (lower(name));

create table public.models (
    model_id                integer generated by default as identity primary key,
    brand_id                integer not null references public.brands (brand_id),
    name                    text    not null,
    market_new_price_mkd    numeric,   -- медијана од огласите за нов уред
    market_sample_size      integer,   -- од колку такви огласи
    estimated_new_price_mkd numeric,   -- LLM-проценка
    estimated_at            timestamptz
);
create unique index models_brand_name_lower_key on public.models (brand_id, lower(name));

-- cluster_id го доделува Clustering Agent (KMeans), затоа не е identity.
create table public.clusters (
    cluster_id integer primary key,
    label      text
);


-- 2. Пополнување на шифрарниците од постојните огласи -------------------

-- 89 огласи од pazar3 се внесени од помошен spider без source; изворот се
-- чита од самото URL.
update public.ads set source = 'pazar3'
where nullif(trim(source), '') is null and ad_url like '%pazar3.mk/%';
update public.ads set source = 'reklama5'
where nullif(trim(source), '') is null and ad_url like '%reklama5.mk/%';

insert into public.sources (name)
select distinct source from public.ads where nullif(trim(source), '') is not null;

update public.sources set base_url = 'https://www.pazar3.mk' where name = 'pazar3';
update public.sources set base_url = 'https://reklama5.mk'   where name = 'reklama5';

insert into public.categories (source_id, name)
select distinct s.source_id, trim(a.category)
from public.ads a
join public.sources s on s.name = a.source
where nullif(trim(a.category), '') is not null;

insert into public.locations (name)
select distinct trim(location) from public.ads where nullif(trim(location), '') is not null;

-- За секој бренд се зема најчестото пишување („HP“, а не „Hp“).
insert into public.brands (name)
select distinct on (lower(trim(brand))) trim(brand)
from public.ads
where nullif(trim(brand), '') is not null
group by trim(brand)
order by lower(trim(brand)), count(*) desc, trim(brand);

-- Брендови што постојат само во кешот на проценки (без оглас).
insert into public.brands (name)
select distinct on (lower(trim(e.brand))) trim(e.brand)
from public.model_price_estimates e
where nullif(trim(e.brand), '') is not null
  and not exists (select 1 from public.brands b where lower(b.name) = lower(trim(e.brand)))
order by lower(trim(e.brand)), trim(e.brand);

insert into public.models (brand_id, name)
select distinct on (b.brand_id, lower(trim(a.model))) b.brand_id, trim(a.model)
from public.ads a
join public.brands b on lower(b.name) = lower(trim(a.brand))
where nullif(trim(a.model), '') is not null
group by b.brand_id, trim(a.model)
order by b.brand_id, lower(trim(a.model)), count(*) desc, trim(a.model);

-- Модели што постојат само во кешот на проценки (без оглас).
insert into public.models (brand_id, name)
select distinct on (b.brand_id, lower(trim(e.model))) b.brand_id, trim(e.model)
from public.model_price_estimates e
join public.brands b on lower(b.name) = lower(trim(e.brand))
where nullif(trim(e.model), '') is not null
  and not exists (
      select 1 from public.models m
      where m.brand_id = b.brand_id and lower(m.name) = lower(trim(e.model)))
order by b.brand_id, lower(trim(e.model)), trim(e.model);

-- Проценета нова цена (LLM кеш) -> models
update public.models m
set estimated_new_price_mkd = e.estimated_new_price_mkd,
    estimated_at            = e.estimated_at
from public.model_price_estimates e
join public.brands b on lower(b.name) = lower(trim(e.brand))
where m.brand_id = b.brand_id
  and lower(m.name) = lower(trim(e.model));

-- Пазарна нова цена -> models (медијаната што Reference Price Agent ја
-- пресметал за моделот). Кај 9 модели огласите имаат различни вредности од
-- постари извршувања; се зема онаа од последно скрапираниот оглас, а агентот
-- ја пресметува одново при следното извршување.
update public.models m
set market_new_price_mkd = r.reference_new_price_mkd,
    market_sample_size   = r.reference_sample_size
from (
    select distinct on (b.brand_id, lower(trim(a.model)))
           b.brand_id, lower(trim(a.model)) as model_lower,
           a.reference_new_price_mkd, a.reference_sample_size
    from public.ads a
    join public.brands b on lower(b.name) = lower(trim(a.brand))
    where a.reference_source = 'marketplace'
      and a.reference_new_price_mkd is not null
      and nullif(trim(a.model), '') is not null
    order by b.brand_id, lower(trim(a.model)), a.scraped_at desc nulls last
) r
where m.brand_id = r.brand_id
  and lower(m.name) = r.model_lower;

-- Кластери: само од производите (кај нив етикетите се конзистентни).
insert into public.clusters (cluster_id, label)
select distinct on (cluster_id) cluster_id, cluster_label
from public.ads
where cluster_id is not null and ad_type = 'product'
group by cluster_id, cluster_label
order by cluster_id, count(*) desc;


-- 3. ads: надворешни клучеви и цена -------------------------------------

alter table public.ads
    add column source_id    integer references public.sources (source_id),
    add column category_id  integer references public.categories (category_id),
    add column location_id  integer references public.locations (location_id),
    add column price_amount numeric;

update public.ads a set source_id = s.source_id
from public.sources s where s.name = a.source;

update public.ads a set category_id = c.category_id
from public.categories c
where c.source_id = a.source_id and c.name = trim(a.category);

update public.ads a set location_id = l.location_id
from public.locations l where l.name = trim(a.location);

-- Оригиналниот износ во валутата на огласот. price_mkd/price_eur веќе се
-- бројно парсирани од текстот, па износот се зема од соодветната од нив.
update public.ads
set price_amount = case currency
                       when 'EUR' then price_eur
                       when 'MKD' then price_mkd
                   end
where currency in ('EUR', 'MKD');

-- 4.477 огласи (скрапирани 09.07–20.09) имаат валута и оригинален износ,
-- но пресметаните price_eur/price_mkd им се избришани: парсерот запишуваше
-- во пакети каде полињата за цена ги имаше само кај огласите со поправена
-- цена, па кај другите во истиот пакет стануваа NULL. Износот се враќа од
-- оригиналниот текст.
update public.ads
set price_amount = price::numeric
where price_amount is null
  and currency in ('EUR', 'MKD')
  and price ~ '^[0-9]+(\.[0-9]+)?$';

-- Неколку десетици се во суров облик („4.500 МКД“, „350 €“): македонски
-- формат, точка за илјадници и запирка за децимали, исто како normalize.py.
update public.ads
set price_amount = replace(
        regexp_replace(substring(price from '^[0-9.,[:space:]]+'), '[.[:space:]]', '', 'g'),
        ',', '.')::numeric
where price_amount is null
  and currency in ('EUR', 'MKD')
  and price ~ '^[0-9]';

-- Бројна цена без запишана валута: пресметана е во денари.
update public.ads
set price_amount = price_mkd, currency = 'MKD'
where currency is null and price_mkd is not null;

alter table public.ads
    add constraint ads_currency_check check (currency in ('MKD', 'EUR'));

-- price_mkd станува генерирана колона: базата сама ја пресметува од
-- износот и валутата (фиксен курс 61.5, како во normalize.py), па никогаш
-- не може да се разликува од оригиналот.
alter table public.ads drop column price_mkd;
alter table public.ads
    add column price_mkd numeric
    generated always as (
        case currency
            when 'MKD' then price_amount
            when 'EUR' then round(price_amount * 61.5, 2)
        end
    ) stored;


-- 4. ad_analysis: резултатите од агентите (1 : 1 со ads) ----------------

create table public.ad_analysis (
    ad_url             text primary key references public.ads (ad_url) on delete cascade,
    ad_type            text,
    is_electronics     boolean,
    brand_id           integer references public.brands (brand_id),
    model_id           integer references public.models (model_id),
    cluster_id         integer references public.clusters (cluster_id) on delete set null,
    seller_notes       text,
    phone              text,
    delivery_available boolean default false,
    reference_source   text check (reference_source in ('marketplace', 'llm_estimate')),
    price_vs_new_ratio numeric,
    good_price_deal    boolean,
    llm_parsed_at      timestamptz
);

insert into public.ad_analysis (
    ad_url, ad_type, is_electronics, brand_id, model_id, cluster_id,
    seller_notes, phone, delivery_available,
    reference_source, price_vs_new_ratio, good_price_deal, llm_parsed_at)
select
    a.ad_url,
    a.ad_type,
    a.is_electronics,
    b.brand_id,
    m.model_id,
    -- огласите што подоцна станаа услуга или „барам“ чуваа стар кластер;
    -- тие не се кластерираат, па остануваат без кластер
    case when a.ad_type = 'product' then k.cluster_id end,
    a.seller_notes,
    a.phone,
    a.delivery_available,
    -- 1.370 огласи сè уште се споредени со Setec, кој е пензиониран: тие
    -- споредби не се пренесуваат (агентот ги пресметува одново)
    case when a.reference_source <> 'setec' then a.reference_source end,
    case when a.reference_source <> 'setec' then a.price_vs_new_ratio end,
    case when a.reference_source = 'setec' then false else a.good_price_deal end,
    a.llm_parsed_at
from public.ads a
left join public.brands   b on lower(b.name) = lower(trim(a.brand))
left join public.models   m on m.brand_id = b.brand_id and lower(m.name) = lower(trim(a.model))
left join public.clusters k on k.cluster_id = a.cluster_id;


